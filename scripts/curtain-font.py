"""Build src/components/load-curtain.css: an inline @font-face of Geist Mono
(OFL) at weight 760, cut to P, A and X, with the X redrawn as one contour that
laps the "\\" bar and then the "/" bar from the point where their left edges
cross. Every font draws X as a single merged outline, so a stroke animation
traces its silhouette; this X makes the load curtain draw one line, then the
second over it, and still fills solid.

  python3 scripts/curtain-font.py path/to/GeistMono-Variable.woff2
"""

import base64
import io
import sys

from fontTools import subset
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

WEIGHT = 760
OUT = "src/components/load-curtain.css"


def crossing(a, b, c, d):
    """Where line a-b meets line c-d."""
    (x1, y1), (x2, y2), (x3, y3), (x4, y4) = a, b, c, d
    den = (x1 - x2) * (y3 - y4) - (y1 - y2) * (x3 - x4)
    t = ((x1 - x3) * (y3 - y4) - (y1 - y3) * (x3 - x4)) / den
    return (x1 + t * (x2 - x1), y1 + t * (y2 - y1))


def main(src: str) -> None:
    font = instancer.instantiateVariableFont(TTFont(src), {"wght": WEIGHT})
    options = subset.Options()
    options.hinting = False
    options.layout_features = []
    options.flavor = "woff2"
    sub = subset.Subsetter(options)
    sub.populate(text="PAX")
    sub.subset(font)

    glyph = font.getBestCmap()[ord("X")]
    points = [p for op, args in record(font, glyph) for p in args]
    # Geist's merged X, clockwise from bottom-left: the four bar ends.
    bl0, _, tl0, tl1, _, tr0, tr1, _, br1, br0, _, bl1 = points
    # "\" runs tl0-tl1 down to br0-br1; "/" runs bl0-bl1 up to tr0-tr1.
    start = crossing(br0, tl0, bl0, tr0)
    lap = [start, tl0, tl1, br1, br0, start, tr0, tr1, bl1, bl0]

    pen = TTGlyphPen(None)
    pen.moveTo(round_pt(lap[0]))
    for p in lap[1:]:
        pen.lineTo(round_pt(p))
    pen.closePath()
    font["glyf"][glyph] = pen.glyph()
    font["glyf"][glyph].recalcBounds(font["glyf"])

    for record_ in font["name"].names:
        if record_.nameID in (1, 4, 16):
            record_.string = "PAX Curtain"
        elif record_.nameID == 6:
            record_.string = "PAXCurtain"
    font.flavor = "woff2"
    buf = io.BytesIO()
    font.save(buf)
    data = base64.b64encode(buf.getvalue()).decode()
    with open(OUT, "w") as f:
        f.write(
            "/* Generated by scripts/curtain-font.py; Geist Mono, SIL Open Font License 1.1. */\n"
            "@font-face {\n"
            '  font-family: "PAX Curtain";\n'
            f'  src: url(data:font/woff2;base64,{data}) format("woff2");\n'
            "  font-weight: 100 900;\n"
            "  font-display: block;\n"
            "}\n"
        )
    print(f"wrote {OUT}")


def record(font, glyph):
    from fontTools.pens.recordingPen import RecordingPen

    pen = RecordingPen()
    font.getGlyphSet()[glyph].draw(pen)
    return [(op, args) for op, args in pen.value if args]


def round_pt(p):
    return (round(p[0]), round(p[1]))


if __name__ == "__main__":
    main(sys.argv[1])
